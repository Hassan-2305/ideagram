"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import { usePathname, useRouter, useSearchParams } from "next/navigation";
import { Grid3x3, RefreshCw, Rows3, Search, SlidersHorizontal, X } from "lucide-react";
import { api, errorMessage } from "@/lib/client";
import { CATEGORIES, type Idea } from "@/lib/types";
import { IdeaPost, IdeaPostSkeleton, IdeaTile } from "./idea-post";

type View = "grid" | "feed";
import type { IdeaState } from "./idea-actions";
import { useApp } from "./providers";
import { Button, ButtonLink, Chip, cx, EmptyState, Select } from "./ui";

interface FeedResponse {
  items: { idea: Idea; reason?: string }[];
  nextCursor: number | null;
  total: number;
  states: Record<string, IdeaState>;
}

const VIEW_KEY = "ig.feed-view";
const SORTS = [
  { value: "for-you", label: "For you" },
  { value: "newest", label: "Newest" },
  { value: "popular", label: "Most saved" },
  { value: "quick", label: "Quick builds" },
];
const SOURCES = [
  { value: "", label: "All sources" },
  { value: "editorial", label: "Idea Gym Editorial" },
  { value: "community", label: "Global: HN + GitHub" },
  { value: "hackernews", label: "Hacker News" },
  { value: "github", label: "GitHub" },
  { value: "mine", label: "Generated by me" },
];

export function DiscoverFeed({ initial }: { initial: FeedResponse }) {
  const router = useRouter();
  const pathname = usePathname();
  const sp = useSearchParams();
  const { user } = useApp();
  const category = sp.get("category") ?? "";
  const sort = sp.get("sort") ?? "for-you";
  const source = sp.get("source") ?? "";
  const difficulty = sp.get("difficulty") ?? "";
  const q = sp.get("q") ?? "";

  const [view, setView] = useState<View>("grid");
  const [data, setData] = useState(initial);
  const [loading, setLoading] = useState(false);
  const [loadingMore, setLoadingMore] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [query, setQuery] = useState(q);
  const [filtersOpen, setFiltersOpen] = useState(false);
  const first = useRef(true);

  useEffect(() => {
    try {
      const v = localStorage.getItem(VIEW_KEY) as View | null;
      // Hydration-safe: the server cannot know the saved view, so read it after mount.
      // eslint-disable-next-line react-hooks/set-state-in-effect
      if (v === "grid" || v === "feed") setView(v);
    } catch {
      /* ignore */
    }
  }, []);

  const changeView = (v: View) => {
    setView(v);
    try {
      localStorage.setItem(VIEW_KEY, v);
    } catch {
      /* ignore */
    }
  };

  const qs = useCallback(
    (cursor = 0) => {
      const p = new URLSearchParams();
      if (category) p.set("category", category);
      if (sort) p.set("sort", sort);
      if (source) p.set("source", source);
      if (difficulty) p.set("difficulty", difficulty);
      if (q) p.set("q", q);
      if (cursor) p.set("cursor", String(cursor));
      return p.toString();
    },
    [category, sort, source, difficulty, q],
  );

  useEffect(() => {
    if (first.current) {
      first.current = false;
      return;
    }
    const ctrl = new AbortController();
    setLoading(true);
    setError(null);
    api<FeedResponse>(`/api/feed?${qs()}`, { signal: ctrl.signal })
      .then(setData)
      .catch((e) => !(e instanceof DOMException) && setError(errorMessage(e)))
      .finally(() => !ctrl.signal.aborted && setLoading(false));
    return () => ctrl.abort();
  }, [qs]);

  // Keep the input in sync when the URL query changes (e.g. "Clear search").
  const [syncedQ, setSyncedQ] = useState(q);
  if (syncedQ !== q) {
    setSyncedQ(q);
    setQuery(q);
  }

  const setParam = (key: string, value: string) => {
    const p = new URLSearchParams(sp.toString());
    if (value) p.set(key, value);
    else p.delete(key);
    router.replace(`${pathname}?${p.toString()}`, { scroll: false });
  };

  const loadMore = async () => {
    if (data.nextCursor == null) return;
    setLoadingMore(true);
    try {
      const next = await api<FeedResponse>(`/api/feed?${qs(data.nextCursor)}`);
      setData((d) => ({ ...next, items: [...d.items, ...next.items.filter((x) => !d.items.some((y) => y.idea.id === x.idea.id))], states: { ...d.states, ...next.states } }));
    } catch (e) {
      setError(errorMessage(e));
    } finally {
      setLoadingMore(false);
    }
  };

  const activeFilters = [source, difficulty].filter(Boolean).length;

  return (
    <div>
      {/* Search + controls */}
      <div className="flex flex-col gap-3 md:flex-row md:items-center">
        <form
          className="relative flex-1"
          onSubmit={(e) => {
            e.preventDefault();
            setParam("q", query.trim());
          }}
        >
          <Search size={16} className="pointer-events-none absolute left-3.5 top-1/2 z-10 -translate-y-1/2 text-ink-3" />
          <input
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder="Search problems, technologies, ideas…"
            aria-label="Search the feed"
            className="glass h-11 w-full rounded-full pl-10 pr-10 text-[15px] text-ink placeholder:text-ink-3 focus:border-line-strong focus:outline-none"
          />
          {q ? (
            <button type="button" onClick={() => setParam("q", "")} aria-label="Clear search" className="absolute right-2 top-1/2 -translate-y-1/2 rounded-lg p-1.5 text-ink-3 hover:text-ink">
              <X size={15} />
            </button>
          ) : null}
        </form>
        <div className="flex min-w-0 items-center gap-2">
          <div role="radiogroup" aria-label="Sort" className="glass no-scrollbar flex min-w-0 flex-1 overflow-x-auto rounded-full p-1 md:flex-none">
            {SORTS.map((s) => (
              <button
                key={s.value}
                role="radio"
                aria-checked={sort === s.value}
                onClick={() => setParam("sort", s.value === "for-you" ? "" : s.value)}
                className={cx("h-8 shrink-0 whitespace-nowrap rounded-full px-3 text-[13px] font-semibold transition-colors", sort === s.value ? "bg-surface-3 text-ink" : "text-ink-3 hover:text-ink")}
              >
                {s.label}
              </button>
            ))}
          </div>
          <button
            onClick={() => setFiltersOpen((o) => !o)}
            aria-expanded={filtersOpen}
            className={cx("glass relative flex h-10 shrink-0 items-center gap-2 rounded-full px-3.5 text-[13px] font-semibold", filtersOpen || activeFilters ? "text-ink ring-1 ring-[var(--ring)]" : "text-ink-2")}
          >
            <SlidersHorizontal size={15} />
            <span className="hidden sm:inline">Filters</span>
            {activeFilters ? <span className="grid h-4.5 min-w-4.5 place-items-center rounded-full bg-accent px-1 text-[10px] font-semibold text-accent-ink">{activeFilters}</span> : null}
          </button>
          <div role="radiogroup" aria-label="Layout" className="glass flex shrink-0 rounded-full p-1">
            {(
              [
                ["grid", Grid3x3, "Grid"],
                ["feed", Rows3, "Posts"],
              ] as const
            ).map(([v, Icon, label]) => (
              <button key={v} role="radio" aria-checked={view === v} aria-label={label} title={label} onClick={() => changeView(v)} className={cx("grid h-8 w-8 place-items-center rounded-full transition", view === v ? "bg-brand" : "text-ink-3 hover:text-ink")}>
                <Icon size={16} />
              </button>
            ))}
          </div>
        </div>
      </div>

      {filtersOpen ? (
        <div className="glass mt-3 grid gap-3 rounded-3xl p-4 animate-fade-in sm:grid-cols-3">
          <div>
            <label htmlFor="f-source" className="mb-1.5 block text-[12px] text-ink-3">
              Source
            </label>
            <Select id="f-source" value={source} onChange={(e) => setParam("source", e.target.value)}>
              {SOURCES.filter((s) => s.value !== "mine" || user).map((s) => (
                <option key={s.value} value={s.value}>
                  {s.label}
                </option>
              ))}
            </Select>
          </div>
          <div>
            <label htmlFor="f-diff" className="mb-1.5 block text-[12px] text-ink-3">
              Difficulty
            </label>
            <Select id="f-diff" value={difficulty} onChange={(e) => setParam("difficulty", e.target.value)}>
              <option value="">Any difficulty</option>
              <option value="beginner">Beginner</option>
              <option value="intermediate">Intermediate</option>
              <option value="advanced">Advanced</option>
            </Select>
          </div>
          <div className="flex items-end gap-2">
            <Button variant="ghost" onClick={() => router.replace(pathname)} className="flex-1">
              Reset all
            </Button>
          </div>
        </div>
      ) : null}

      {/* Category rail */}
      <div className="no-scrollbar -mx-4 mt-4 flex gap-2 overflow-x-auto px-4 pb-1 md:mx-0 md:flex-wrap md:px-0">
        <Chip active={!category} onClick={() => setParam("category", "")}>
          All
        </Chip>
        {CATEGORIES.map((c) => (
          <Chip key={c.slug} active={category === c.slug} onClick={() => setParam("category", category === c.slug ? "" : c.slug)}>
            {c.label}
          </Chip>
        ))}
      </div>

      <div className="mt-6 flex items-center justify-between text-[13px] text-ink-3" aria-live="polite">
        <span>
          {loading ? "Loading…" : `${data.total} idea${data.total === 1 ? "" : "s"}`}
          {q ? ` matching “${q}”` : ""}
          {sort === "for-you" && !q ? " · ranked for you, with a few blind spots mixed in" : ""}
        </span>
      </div>

      {error ? (
        <div className="mt-4 flex items-center justify-between rounded-xl bg-danger-soft px-4 py-3 text-sm text-danger">
          {error}
          <Button size="sm" variant="ghost" onClick={() => router.refresh()}>
            <RefreshCw size={14} /> Retry
          </Button>
        </div>
      ) : null}

      <div className={cx("mt-4", loading && "opacity-60 transition-opacity")}>
        {loading && data.items.length === 0 ? (
          view === "grid" ? (
            <div className="grid grid-cols-3 gap-1.5 sm:gap-3">
              {Array.from({ length: 9 }).map((_, i) => (
                <div key={i} className="skeleton aspect-square rounded-2xl" />
              ))}
            </div>
          ) : (
            <div className="mx-auto max-w-[500px] space-y-6">
              <IdeaPostSkeleton />
            </div>
          )
        ) : data.items.length === 0 ? (
          <EmptyState
            icon={<Search size={20} />}
            title={q ? "Nothing matches that yet" : "No ideas in this view"}
            description={q ? "Try a broader term, remove a filter, or ask the AI Lab to generate ideas on this topic." : "Clear a filter or pick another category."}
            action={
              <div className="flex gap-2">
                <Button variant="secondary" onClick={() => router.replace(pathname)}>
                  Clear filters
                </Button>
                {q ? <ButtonLink href={`/lab?topic=${encodeURIComponent(q)}`}>Generate ideas</ButtonLink> : null}
              </div>
            }
          />
        ) : view === "feed" ? (
          <div className="mx-auto max-w-[500px] space-y-6">
            {data.items.map((it, i) => (
              <IdeaPost key={it.idea.id} idea={it.idea} state={data.states[it.idea.id]} reason={it.reason} index={i} />
            ))}
          </div>
        ) : (
          <div className="grid grid-cols-3 gap-1.5 sm:gap-3">
            {data.items.map((it, i) => (
              <IdeaTile key={it.idea.id} idea={it.idea} index={i} />
            ))}
          </div>
        )}
      </div>

      {data.nextCursor != null ? (
        <div className="mt-10 flex flex-col items-center gap-2">
          <Button variant="secondary" onClick={loadMore} loading={loadingMore}>
            Show more ideas
          </Button>
          <p className="text-[12px] text-ink-3">
            Showing {data.items.length} of {data.total}. Found something good? Save it before moving on.
          </p>
        </div>
      ) : data.items.length > 0 ? (
        <p className="mt-10 text-center text-[13px] text-ink-3">You&apos;ve reached the end of this view — a good moment to remix what you saved or take today&apos;s challenge.</p>
      ) : null}
    </div>
  );
}
