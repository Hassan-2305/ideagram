// Core domain types shared by server and client code.

export const CATEGORIES = [
  { slug: "ai-ml", label: "AI & Machine Learning" },
  { slug: "devtools", label: "Developer Tools" },
  { slug: "productivity", label: "Productivity" },
  { slug: "startups", label: "Startups" },
  { slug: "education", label: "Education" },
  { slug: "healthcare", label: "Healthcare" },
  { slug: "sustainability", label: "Sustainability" },
  { slug: "finance", label: "Finance" },
  { slug: "hardware", label: "Hardware" },
  { slug: "automation", label: "Automation" },
  { slug: "design", label: "Design" },
  { slug: "social-impact", label: "Social Impact" },
  { slug: "experimental", label: "Experimental Technology" },
  { slug: "open-source", label: "Open Source" },
  { slug: "everyday", label: "Everyday Problems" },
] as const;

export type CategorySlug = (typeof CATEGORIES)[number]["slug"];
export const CATEGORY_SLUGS = CATEGORIES.map((c) => c.slug) as [CategorySlug, ...CategorySlug[]];

export function categoryLabel(slug: string): string {
  return CATEGORIES.find((c) => c.slug === slug)?.label ?? slug;
}

export const DIFFICULTIES = ["beginner", "intermediate", "advanced"] as const;
export type Difficulty = (typeof DIFFICULTIES)[number];

/** Where an idea came from. Never fabricate community/external sources. */
export type SourceKind =
  | "editorial" // written by the Idea Gym team, shipped with the app
  | "hackernews" // ingested from the public Hacker News Algolia API
  | "github" // ingested from the public GitHub search API
  | "ai" // generated by Claude for a user
  | "remix" // produced by the remix engine
  | "user"; // written by a user

export interface Idea {
  id: string;
  title: string;
  summary: string;
  problem: string;
  solution: string;
  insight: string; // why it matters
  category: CategorySlug;
  difficulty: Difficulty;
  buildTime: string; // e.g. "1 weekend", "2–3 weeks"
  stack: string[];
  tags: string[];
  sourceKind: SourceKind;
  sourceName: string; // "Idea Gym Editorial", "Hacker News", "GitHub"
  sourceUrl: string | null;
  creator: string | null;
  publishedAt: string | null; // ISO
  createdAt: string; // ISO
  ownerId: string | null; // set for private AI/remix/user ideas
  isPublic: boolean;
  details: IdeaDetails | null; // rich structure for generated ideas
  parentIds: string[]; // remix lineage
  likeCount: number;
  saveCount: number;
}

/** Optional long-form structure (AI Lab output, remixes). */
export interface IdeaDetails {
  audience?: string;
  alternatives?: string[];
  differentiation?: string;
  mvp?: string[];
  implementation?: string;
  challenges?: string[];
  extensions?: string[];
  // remix-specific
  combined?: string[];
  whyItWorks?: string;
  opportunity?: string;
  feasibility?: string;
  prototype?: string[];
}

export const VAULT_STATUSES = [
  "interesting",
  "exploring",
  "planned",
  "building",
  "completed",
  "archived",
] as const;
export type VaultStatus = (typeof VAULT_STATUSES)[number];

export interface SessionUser {
  id: string;
  email: string;
  name: string;
}

export type InteractionKind = "view" | "like" | "save" | "hide" | "remix" | "build" | "interesting";
